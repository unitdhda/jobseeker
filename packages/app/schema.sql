create table public.telegram_updates (
  update_id bigint not null,
  received_at timestamptz not null default now(),
  state text not null default 'processing',
  attempts integer not null default 1,
  lease_expires_at timestamptz,
  completed_at timestamptz,
  last_error text,
  constraint telegram_updates_state_check check (state = any (array['processing','completed','failed'])),
  constraint telegram_updates_pkey primary key (update_id)
);

create index telegram_updates_cleanup_idx on public.telegram_updates using btree (received_at);
create index usage_events_kind_time_idx on public.usage_events using btree (kind, occurred_at desc);
create index usage_events_user_kind_time_idx on public.usage_events using btree (user_id, kind, occurred_at desc);
create index user_state_expiry_idx on public.user_state using btree (expires_at);
create index matches_user_state_idx on public.matches using btree (user_id, state);
create index matches_user_score_idx on public.matches using btree (user_id, llm_score desc) where (llm_score is not null);
create index search_units_due_idx on public.search_units using btree (platform, next_run_at) where (retired_at is null);
create index vacancies_canonical_idx on public.vacancies using btree (canonical_fingerprint);
create index vacancies_normalization_queue_idx on public.vacancies using btree (lifecycle_status, normalization_retry_at, published_at);
create index vacancies_search_idx on public.vacancies using gin (search_vector);
