create table public.user_state (
  user_id text not null,
  kind text not null,
  state jsonb not null default '{}'::jsonb,
  expires_at timestamptz not null,
  updated_at timestamptz not null default now(),
  constraint user_state_pkey primary key (user_id, kind),
  constraint user_state_user_id_fkey foreign key (user_id) references users(user_id) on delete cascade
