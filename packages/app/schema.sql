create table public.unit_subscriptions (
  unit_id text not null,
  user_id text not null,
  search_name text not null,
  source_search jsonb not null,
  created_at timestamptz not null default now(),
  constraint unit_subscriptions_pkey primary key (unit_id, user_id),
  constraint unit_subscriptions_unit_id_fkey foreign key (unit_id) references search_units(unit_id) on delete cascade,
  constraint unit_subscriptions_user_id_fkey foreign key (user_id) references users(user_id) on delete cascade
