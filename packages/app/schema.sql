-- Jobseeker PostgreSQL schema — the single schema of record.
--
-- Applied to an empty database by `jobseeker db init` (or psql). There are no incremental migrations: a schema
-- change ships as a new revision of this file plus, when needed, a documented one-off statement for live
-- deployments.


create table public.users (
  user_id text not null,
  chat_id text not null,
  username text,
  display_name text not null,
  status text not null,
  is_owner smallint not null default 0,
  requested_at timestamptz,
  approved_at timestamptz,
  updated_at timestamptz not null,
  delivery_start_minutes integer,
  delivery_end_minutes integer,
  digest_minutes integer,
  delivery_timezone text,
  last_digest_at timestamptz,
  -- Interface language: the one chosen with /language, or the Telegram client language first seen for this user.
  -- Null means the deployment default; an unrecognised value is read as the default rather than rejected.
  locale text,
  constraint users_is_owner_check check (is_owner = any (array[0, 1])),
  constraint users_status_check check (status = any (array['unregistered','pending','approved','rejected','revoked'])),
  constraint users_pkey primary key (user_id),
  constraint users_chat_id_key unique (chat_id)
);

create table public.cv_documents (
  user_id text not null,
  cv_sha256 text not null,
  cv_text text not null,
  document_json jsonb not null,
  source_format text not null,
  original_filename text not null,
  media_type text not null,
  parser_name text not null,
  parser_version text not null,
  -- The per-platform LLM-generated search profiles: the source that demand compilation reads.
  search_profiles jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null,
  constraint cv_documents_pkey primary key (user_id),
  constraint cv_documents_user_id_fkey foreign key (user_id) references users(user_id) on delete cascade
);

create table public.vacancies (
  id bigint generated by default as identity,
  source text not null,
  source_id text not null,
  apply_id text,
  name text,
  employer text,
  area text,
  salary_from integer,
  salary_to integer,
  salary_currency text,
  salary_gross smallint,
  experience text,
  employment text,
  schedule text,
  work_format text,
  description text,
  key_skills_json jsonb,
  url text not null,
  published_at timestamptz not null,
  source_query text,
  content_hash text,
  canonical_fingerprint text,
  first_seen_at timestamptz not null,
  updated_at timestamptz not null,
  search_vector tsvector generated always as (to_tsvector('simple'::regconfig, ((((((coalesce(name, ''::text) || ' '::text) || coalesce(employer, ''::text)) || ' '::text) || coalesce(description, ''::text)) || ' '::text) || coalesce((key_skills_json)::text, ''::text)))) stored,
  listing_search_name text,
  listing_title text,
  listing_summary text,
  listing_payload jsonb,
  listing_hash text,
  lifecycle_status text,
  normalized_vacancy_id bigint,
  normalization_attempts integer not null default 0,
  normalization_error text,
  normalization_retry_at timestamptz,
  last_seen_at timestamptz,
  last_checked_at timestamptz,
  constraint vacancies_apply_id_check check (apply_id ~ '^[a-z]{6}$'::text),
  constraint vacancies_lifecycle_status_check check (lifecycle_status = any (array['discovered','queued','filtered','normalizing','normalized','duplicate','failed','closed'])),
  constraint vacancies_salary_gross_check check ((salary_gross is null) or (salary_gross = any (array[0, 1]))),
  constraint vacancies_pkey primary key (id),
  constraint vacancies_apply_id_key unique (apply_id),
  constraint vacancies_source_source_id_key unique (source, source_id),
  constraint vacancies_normalized_vacancy_id_fkey foreign key (normalized_vacancy_id) references vacancies(id) on delete set null
);

create table public.search_units (
