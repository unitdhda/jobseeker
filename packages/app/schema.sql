create table public.matches (
  user_id text not null,
  vacancy_id bigint not null,
  state text not null default 'matched',
  lexical_score integer,
  -- The prefilter evidence exactly as it stood at match time. Paired with llm_score these rows are the
  -- calibration's training data; they are never recomputed, because the CV may have changed since.
  lexical_regex_score integer,
  lexical_cosine double precision,
  -- The two signals lexical_regex_score collapses together, kept apart so a refit can weigh them separately.
  -- Both 0..1; null on rows matched before these columns existed.
  lexical_title_similarity double precision,
  lexical_skill_coverage double precision,
  llm_score integer,
  score_updated_at timestamptz,
  alert_primary_track text,
  alert_summary text,
  alert_reasons jsonb,
  alert_gaps jsonb,
  application_status text,
  application_error text,
  application_requested_at timestamptz,
  application_updated_at timestamptz,
  -- Delivered artifacts by kind: the Telegram file_id (cv) or text (letter) plus the cv hash it was built from,
  -- so a repeat request resends instantly instead of regenerating.
  application_artifacts jsonb not null default '{}'::jsonb,
  matched_at timestamptz not null,
  updated_at timestamptz not null,
  constraint matches_state_check check (state = any (array['matched','queued','scored','alerted','digested','skipped','applying','applied','expired'])),
  constraint matches_application_status_check check (application_status = any (array['generating','ready','failed'])),
  constraint matches_llm_score_check check ((llm_score >= 0) and (llm_score <= 100)),
  constraint matches_pkey primary key (user_id, vacancy_id),
  constraint matches_user_id_fkey foreign key (user_id) references users(user_id) on delete cascade,
  constraint matches_vacancy_id_fkey foreign key (vacancy_id) references vacancies(id) on delete cascade
);

-- Role-token equivalences mined from career-profile title variants (engine mineRoleEquivalences). Consulted at
-- compare time by the prefilter and unit adoption; never by unit-identity hashing. Rebuilt from profiles, so
-- rows are derived data — truncating this table only narrows matching until the next mining pass.
create table public.role_equivalences (
  token_a text not null,
  token_b text not null,
  support integer not null default 1,
  updated_at timestamptz not null default now(),
  constraint role_equivalences_pkey primary key (token_a, token_b),
  constraint role_equivalences_order_check check (token_a < token_b)
);

-- Every calibration the refit stage ever produced, accepted or not; the active model is the newest accepted
-- row, and rolling back is flipping accepted off. Coefficients follow the engine's prefilterCalibrationSchema.
create table public.calibrations (
  id bigint generated by default as identity,
  created_at timestamptz not null default now(),
  coefficients jsonb not null,
  metrics jsonb not null,
  accepted smallint not null default 0,
  constraint calibrations_accepted_check check (accepted = any (array[0, 1])),
  constraint calibrations_pkey primary key (id)
);

create table public.usage_events (
  id bigint generated by default as identity,
  user_id text not null,
  kind text not null,
  occurred_at timestamptz not null,
  agent text,
  model text,
  input_tokens bigint not null default 0,
  output_tokens bigint not null default 0,
  cache_read_tokens bigint not null default 0,
  cache_write_tokens bigint not null default 0,
  total_tokens bigint not null default 0,
  cost_usd numeric(14,8) not null default 0,
  constraint usage_events_kind_check check (kind = any (array['score','application','search-profile','llm'])),
  constraint usage_events_pkey primary key (id),
  constraint usage_events_user_id_fkey foreign key (user_id) references users(user_id) on delete cascade
);

create table public.accounts (
  user_id text not null,
